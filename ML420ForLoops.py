# This code provides a range of numbers that go up to but not including a designated number
# 1st: The count variable always begins at the number zero
# 2nd: The count variable goes up by one. So like 0, 1, 2, 3 and so on.
# 3rd: The count variable stops at the number before the range number. So if the number is 9, the count stops at 8
for count in range(9):
    print(count)
